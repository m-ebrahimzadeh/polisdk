import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';
import * as esbuild from 'esbuild';

const pkgDir = path.dirname(fileURLToPath(import.meta.url));
const distDir = path.join(pkgDir, 'dist');
const generatedDir = path.join(pkgDir, 'src', 'generated');

fs.rmSync(distDir, { recursive: true, force: true });
fs.mkdirSync(generatedDir, { recursive: true });

// 1. Bundle the browser-injected DOM adapter IIFE script at build time
const bundleResult = await esbuild.build({
  entryPoints: [path.join(pkgDir, 'src/injected-auth-entry.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: ['es2022']
});

const iifeCode = bundleResult.outputFiles[0].text;

// 2. Emit generated TypeScript constant so runtime has zero esbuild or node:fs dependency
fs.writeFileSync(
  path.join(generatedDir, 'injected-bundle-code.ts'),
  `// Auto-generated by build.mjs — DO NOT EDIT\nexport const INJECTED_AUTH_ADAPTER_BUNDLE_CODE: string = ${JSON.stringify(iifeCode)};\n`,
  'utf8'
);

// 3. Compile TypeScript sources and .d.ts declarations
execSync('npx tsc -p tsconfig.json', {
  cwd: pkgDir,
  stdio: 'inherit'
});

// 4. Write standalone IIFE artifact and companion declaration into dist/
fs.writeFileSync(
  path.join(distDir, 'injected-auth-adapters.iife.js'),
  iifeCode,
  'utf8'
);
fs.writeFileSync(
  path.join(distDir, 'injected-auth-adapters.iife.d.ts'),
  `// Type declaration for side-effect IIFE bundle attaching window.__PoliAuthAdapters\nexport {};\n`,
  'utf8'
);

console.log('✅ @polisdk/poliauth-playwright built successfully into dist/');
